import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

/** Emits client/catalog/builtinModules.ts: one static import per SRD RuleModule so Vite and node tests see the same list. */
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const modulesRoot = join(root, "content", "modules");
const names = readdirSync(modulesRoot).filter((name) => existsSync(join(modulesRoot, name, "module.json"))).sort();
const ident = (name) => "m_" + name.replace(/[^a-zA-Z0-9]+/g, "_");
const lines = [
  "// Generated by scripts/generate-client-builtin-modules.mjs — do not edit by hand.",
  "// Every SRD 5.2.1 RuleModule shipped under content/modules, in name order.",
  ...names.map((name) => `import ${ident(name)} from "../../content/modules/${name}/module.json";`),
  "",
  "export const BUILTIN_MODULE_JSON: readonly unknown[] = [",
  ...names.map((name) => `  ${ident(name)},`),
  "];",
  "",
];
writeFileSync(join(root, "client", "catalog", "builtinModules.ts"), lines.join("\n"));
console.log(`builtinModules.ts: ${names.length} modules`);
