import { readdirSync, writeFileSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Emits client/catalog/builtinModules.ts: one static import per SRD module so Vite and node tests see the same list.
 * D314: the SRD is the modules built from its source (content/modules/srd-5.2.1, scripts/srd-build-modules.mjs).
 */
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const modulesRoot = join(root, "content", "modules", "srd-5.2.1");
const names = readdirSync(modulesRoot).filter((name) => name.endsWith(".module.json")).sort();
const ident = (name) => "m_" + name.replace(/[.]module[.]json$/, "").replace(/[^a-zA-Z0-9]+/g, "_");
const lines = [
  "// Generated by scripts/generate-client-builtin-modules.mjs — do not edit by hand.",
  "// Every SRD 5.2.1 module built from the source (content/modules/srd-5.2.1), in name order.",
  ...names.map((name) => `import ${ident(name)} from "../../content/modules/srd-5.2.1/${name}";`),
  "",
  "export const BUILTIN_MODULE_JSON: readonly unknown[] = [",
  ...names.map((name) => `  ${ident(name)},`),
  "];",
  "",
];
writeFileSync(join(root, "client", "catalog", "builtinModules.ts"), lines.join(String.fromCharCode(10)));
console.log(`builtinModules.ts: ${names.length} modules`);
